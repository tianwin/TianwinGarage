def generate_order_id(df: pd.DataFrame, prefix: str = "RO") -> str:
    date_part = app_now().strftime("%Y%m%d")
    pattern = re.compile(rf"^{re.escape(prefix)}-{date_part}-(\d+)$")
    max_sequence = 0

    if df is not None and "Order ID" in df.columns:
        for value in df["Order ID"].dropna():
            match = pattern.match(str(value).strip())
            if match:
                max_sequence = max(max_sequence, int(match.group(1)))

    return f"{prefix}-{date_part}-{max_sequence + 1:03d}"


def ensure_unique_order_id(order_id: str, df: pd.DataFrame, prefix: str = "RO") -> str:
    existing_ids = set()
    if df is not None and "Order ID" in df.columns:
        existing_ids = {
            str(value).strip()
            for value in df["Order ID"].dropna()
            if str(value).strip()
        }

    order_id = str(order_id or "").strip()
    if order_id and order_id not in existing_ids:
        return order_id

    next_id = generate_order_id(df, prefix)
    while next_id in existing_ids:
        head, sequence = next_id.rsplit("-", 1)
        next_id = f"{head}-{int(sequence) + 1:03d}"
    return next_id


def compute_profit_row(row: pd.Series) -> pd.Series:
    # Auto Total Price if missing: Labor + Trip Fee + Part Price
    labor = row.get("Labor")
    trip_fee = row.get("Trip Fee")
    part_cost = row.get("Part Cost")
    part_price = row.get("Part Price")
    total_price = row.get("Total Price")

    if pd.isna(total_price) or total_price == "" or total_price == 0:
        if pd.notna(labor) and pd.notna(part_price):
            trip_fee_value = 0 if pd.isna(trip_fee) or trip_fee == "" else float(trip_fee)
            row["Total Price"] = round(float(labor) + trip_fee_value + float(part_price), 2)
            total_price = row["Total Price"]

    if pd.notna(total_price) and pd.notna(part_cost):
        row["Profit"] = round(float(total_price) - float(part_cost), 2)

    # Round all price fields to 2 decimal places
    for price_col in PRICE_COLUMNS:
        if price_col in row and pd.notna(row.get(price_col)) and row.get(price_col) != "":
            try:
                row[price_col] = round(float(row[price_col]), 2)
            except (ValueError, TypeError):
                pass
    return row


