"""Streamlit Auto Repair Orders app — Google Sheets backend.

Quick setup (Service Account)
-----------------------------
1) In Google Cloud Console:
   - Create/select a project
   - Enable **Google Sheets API**
   - Create a **Service Account** and download the JSON key file

2) Share your target Google Sheet with the service account email
   (it looks like: something@project-id.iam.gserviceaccount.com)

3) Set these environment variables when running Streamlit:

   - GOOGLE_SHEETS_SPREADSHEET_ID : the spreadsheet id (from the URL)
   - GOOGLE_SHEETS_WORKSHEET_NAME : optional, default "Orders"
   - GOOGLE_SERVICE_ACCOUNT_JSON  : path to the downloaded key file
   - GOOGLE_SERVICE_ACCOUNT_JSON_CONTENT : optional full JSON content for hosted deploys

Example:
  export GOOGLE_SHEETS_SPREADSHEET_ID='1AbC...'
  export GOOGLE_SHEETS_WORKSHEET_NAME='Orders'
  export GOOGLE_SERVICE_ACCOUNT_JSON='/path/to/service_account.json'
  streamlit run app_gsheets.py

Notes
-----
- This app requires Google Sheets to be configured. No local storage fallback.
- This app writes the *entire* table back to the sheet when you click Save.
  That keeps things simple and reliable.
- "Total Price" and "Profit" columns are excluded from writes (auto-generated by formulas).
- Editable columns are written by matching Google Sheet header names, so column
  order changes are less likely to shift data into the wrong fields.
- If multiple people will edit concurrently, consider switching to an
  append/update-by-Order-ID strategy.
"""

