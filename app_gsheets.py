def save_orders_gsheets(df: pd.DataFrame) -> list[str]:
    spreadsheet_id, worksheet_name, sa_json_path = _sheets_env()
    service = get_sheets_service(sa_json_path, None if sa_json_path else _service_account_json())
    header_map = sheet_header_map(service, spreadsheet_id, worksheet_name)

    df = normalize_df(df.copy())
    df["Last Updated"] = now_str()

    # Columns to exclude from writing (these are auto-generated by formulas in Google Sheets)
    excluded_cols = FORMULA_COLUMNS
    
    # Get columns to write (all columns except excluded ones)
    cols_to_write = [col for col in COLUMNS if col not in excluded_cols and col in header_map]
    
    skipped_columns = [
        col for col in COLUMNS if col not in excluded_cols and col not in header_map
    ]
    
    # Build rows with proper data types (only writable columns)
    rows = []
    for _, row in df.iterrows():
        row_data = []
        for col in cols_to_write:
            if col in NUMERIC_COLUMNS and col in df.columns:
                val = row[col]
                # Send as number if valid (including 0), otherwise empty string
                if pd.notna(val) and val != "" and str(val).strip().upper() not in ["NONE", "N/A", "NA"]:
                    try:
                        row_data.append(float(val))
                    except (ValueError, TypeError):
                        row_data.append("")
                else:
                    row_data.append("")
            else:
                val = row[col]
                # For text columns, convert to string, handle None/NaN
                if pd.notna(val) and val != "" and str(val).strip().upper() not in ["NONE", "N/A", "NA", "NAN"]:
                    row_data.append(str(val))
                else:
                    row_data.append("")
        rows.append(row_data)
    
    num_rows = len(rows) + 1  # +1 for header row
    
    # Build data for batch update - write column by column to skip protected ones
    # Column letters come from the live sheet headers so layout changes do not shift values.
    batch_data = []
    
    for col_name in cols_to_write:
        write_idx = cols_to_write.index(col_name)
        col_letter = header_map[col_name]
        
        # Extract this column's data from all rows. Do not rewrite row 1 headers:
        # many sheets protect the header row while allowing data rows to be edited.
        column_values = []
        for row in rows:
            column_values.append([row[write_idx]])
        
        range_name = f"{worksheet_name}!{col_letter}2:{col_letter}{num_rows}"
        batch_data.append({
            "range": range_name,
            "column": col_name,
            "values": column_values
        })
    
    # Use batchUpdate to write all columns at once
    body = {
        "valueInputOption": "USER_ENTERED",
        "data": [
            {"range": item["range"], "values": item["values"]}
            for item in batch_data
        ]
    }
    try:
        execute_sheets_request(
            service.spreadsheets().values().batchUpdate(
                spreadsheetId=spreadsheet_id,
                body=body
            ),
            "save",
        )
        return skipped_columns
    except Exception:
        failed_columns = []
        for item in batch_data:
            single_body = {
                "valueInputOption": "USER_ENTERED",
                "data": [{"range": item["range"], "values": item["values"]}],
            }
            try:
                execute_sheets_request(
                    service.spreadsheets().values().batchUpdate(
                        spreadsheetId=spreadsheet_id,
                        body=single_body
                    ),
                    f"save column {item['column']}",
                )
            except Exception:
                failed_columns.append(item["column"])

        if len(failed_columns) == len(batch_data):
            raise
        return skipped_columns + failed_columns


def next_order_row_gsheets(service, spreadsheet_id: str, worksheet_name: str) -> int:
    resp = execute_sheets_request(
        service.spreadsheets().values().get(
            spreadsheetId=spreadsheet_id,
            range=f"{worksheet_name}!A2:S",
        ),
        "find next order row",
    )
    values = resp.get("values", [])
    last_used_offset = 0
    for idx, row_values in enumerate(values, start=1):
        if any(str(cell).strip() for cell in row_values):
            last_used_offset = idx
    return last_used_offset + 2


