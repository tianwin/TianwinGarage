def _streamlit_secret(name: str, default=None):
    try:
        return st.secrets.get(name, default)
    except Exception:
        return default


def _sheets_env() -> Tuple[Optional[str], str, Optional[str]]:
    spreadsheet_id = os.getenv("GOOGLE_SHEETS_SPREADSHEET_ID") or _streamlit_secret(
        "GOOGLE_SHEETS_SPREADSHEET_ID"
    )
    worksheet_name = os.getenv("GOOGLE_SHEETS_WORKSHEET_NAME") or _streamlit_secret(
        "GOOGLE_SHEETS_WORKSHEET_NAME",
        "Orders",
    )
    sa_json_path = os.getenv("GOOGLE_SERVICE_ACCOUNT_JSON") or _streamlit_secret(
        "GOOGLE_SERVICE_ACCOUNT_JSON"
    )
    return spreadsheet_id, worksheet_name, sa_json_path


def _service_account_json() -> Optional[str]:
    json_content = os.getenv("GOOGLE_SERVICE_ACCOUNT_JSON_CONTENT") or _streamlit_secret(
        "GOOGLE_SERVICE_ACCOUNT_JSON_CONTENT"
    )
    if json_content:
        return str(json_content)

    service_account = _streamlit_secret("google_service_account")
    if service_account:
        return json.dumps(dict(service_account))

    return None


def gsheets_enabled() -> bool:
    spreadsheet_id, _, sa_json_path = _sheets_env()
    return bool(spreadsheet_id and (sa_json_path or _service_account_json()) and Credentials and build)


@st.cache_resource
def get_sheets_service(sa_json_path: Optional[str], sa_json: Optional[str]):
    scopes = ["https://www.googleapis.com/auth/spreadsheets"]
    if sa_json:
        creds = Credentials.from_service_account_info(json.loads(sa_json), scopes=scopes)
    else:
        creds = Credentials.from_service_account_file(sa_json_path, scopes=scopes)

    if google_auth_httplib2 is not None and httplib2 is not None:
        authed_http = google_auth_httplib2.AuthorizedHttp(
            creds,
            http=httplib2.Http(timeout=12),
        )
        return build("sheets", "v4", http=authed_http, cache_discovery=False)

    return build("sheets", "v4", credentials=creds, cache_discovery=False)


def get_column_letter(n):
    result = ""
    while n > 0:
        n -= 1
        result = chr(65 + (n % 26)) + result
        n //= 26
    return result


def execute_sheets_request(request, action: str, attempts: int = 2):
    last_error = None
    for attempt in range(1, attempts + 1):
        try:
            return request.execute(num_retries=0)
        except Exception as e:
            last_error = e
            if HttpError is not None and isinstance(e, HttpError):
                status = getattr(e.resp, "status", None)
                if status is not None and 400 <= int(status) < 500:
                    raise
            if attempt == attempts:
                break
            time.sleep(min(2 ** (attempt - 1), 5))

    raise RuntimeError(
        f"Google Sheets {action} failed after {attempts} attempts. "
        "Please check your internet connection and try Reload from source. "
        f"Last error: {last_error}"
    )


def sheet_cell_value(row: pd.Series, col: str):
    numeric_cols = ["Labor", "Part Cost", "Part Price", "Mileage"]
    val = row.get(col, "")
