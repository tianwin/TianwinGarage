def quick_stat_windows(dfx: pd.DataFrame):
    today = pd.Timestamp(datetime.now().date())
    week_start = today - pd.Timedelta(days=today.weekday())
    biweekly_start = week_start - pd.Timedelta(days=7)
    month_start = today.replace(day=1)
    week_end = week_start + pd.Timedelta(days=6)
    biweekly_end = biweekly_start + pd.Timedelta(days=13)
    month_end = month_start + pd.offsets.MonthEnd(0)
    previous_week_start = week_start - pd.Timedelta(days=7)
    previous_biweekly_start = biweekly_start - pd.Timedelta(days=14)
    previous_month_start = (month_start - pd.offsets.MonthBegin(1)).normalize()

    dated = dfx[dfx["Date Parsed"].notna()].copy()
    dated = dated[dated["Date Parsed"].dt.normalize() <= today]
    date_values = dated["Date Parsed"].dt.normalize()

    return [
        (
            "This Week",
            f"Since {week_start:%b %d}",
            dated[date_values >= week_start],
            dated[(date_values >= previous_week_start) & (date_values < week_start)],
            "last full week",
            week_end,
        ),
        (
            "Biweekly",
            f"Since {biweekly_start:%b %d}",
            dated[date_values >= biweekly_start],
            dated[(date_values >= previous_biweekly_start) & (date_values < biweekly_start)],
            "previous full biweek",
            biweekly_end,
        ),
        (
            "Month-to-Date",
            f"Since {month_start:%b %d}",
            dated[date_values >= month_start],
            dated[(date_values >= previous_month_start) & (date_values < month_start)],
            "last full month",
            month_end,
        ),
        ("Overall", "All real orders", dfx, None, "", None),
    ]


def days_left_label(end_date: Optional[pd.Timestamp]) -> str:
    if end_date is None:
        return ""

    today = pd.Timestamp(datetime.now().date())
    days_left = max(int((end_date.normalize() - today).days), 0)
    day_word = "day" if days_left == 1 else "days"
    return f"{days_left} {day_word} left · ends {end_date:%b %d}"


def pct_of_previous(current_value, previous_value) -> str:
    current_value = float(current_value or 0)
    previous_value = float(previous_value or 0)
    if previous_value == 0:
        return "N/A" if current_value else "0%"
    return f"{current_value / previous_value * 100:.0f}%"


def comparison_bar_html(label: str, current_value, previous_value, value_text: str) -> str:
    current_value = float(current_value or 0)
    previous_value = float(previous_value or 0)
    if previous_value == 0:
        percent_text = "N/A" if current_value else "0%"
        bar_width = 0
    else:
        percent = current_value / previous_value * 100
        percent_text = f"{percent:.0f}%"
        bar_width = max(0, min(percent, 100))

    return (
        f'<div class="tw-stat-compare">'
        f'<div class="tw-stat-compare-top">'
        f'<span>{html.escape(label)}</span>'
        f'<strong>{html.escape(value_text)}</strong>'
        f'</div>'
        f'<div class="tw-stat-bar-row">'
        f'<div class="tw-stat-bar" aria-label="{html.escape(label)} {html.escape(percent_text)}">'
        f'<div class="tw-stat-bar-fill" style="width: {bar_width:.0f}%;"></div>'
        f'</div>'
        f'<span class="tw-stat-bar-pct">{html.escape(percent_text)}</span>'
        f'</div>'
        f'</div>'
    )


