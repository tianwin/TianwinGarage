def clean_price_value(value):
    """Clean price values: strip $ and commas, convert (123.45) to -123.45, handle None/N/A."""
    if pd.isna(value) or value == "" or value is None:
        return None
    
    # Convert to string for processing
    val_str = str(value).strip()
    
    # Treat "None", "N/A", "n/a", "NA", "na" as empty
    if val_str.upper() in ["NONE", "N/A", "NA", ""]:
        return None
    
    # Remove $ and commas
    val_str = val_str.replace("$", "").replace(",", "").strip()
    
    # Handle accounting format: (123.45) means negative
    if val_str.startswith("(") and val_str.endswith(")"):
        val_str = "-" + val_str[1:-1]
    
    # Try to convert to float
    try:
        result = float(val_str)
        return result
    except (ValueError, TypeError):
        return None


def normalize_df(df: pd.DataFrame) -> pd.DataFrame:
    """Ensure all required columns exist, order columns, and coerce numeric fields."""
    if df is None or df.empty:
        df = pd.DataFrame(columns=COLUMNS)
    else:
        df = df.copy()
        df.columns = [str(c).strip().lstrip("\ufeff") for c in df.columns]
        df = df.loc[:, [c != "" and c.lower() != "nan" for c in df.columns]]
        df = df.loc[:, ~df.columns.duplicated()].copy()

    for c in COLUMNS:
        if c not in df.columns:
            df[c] = ""

    df = df[COLUMNS].copy()

    # Clean and convert price columns
    for col in PRICE_COLUMNS:
        if col in df.columns:
            df[col] = df[col].apply(clean_price_value)

    if "Labor Time" in df.columns:
        df["Labor Time"] = pd.to_numeric(df["Labor Time"], errors="coerce")
    
    # Handle Mileage separately (no $ or accounting format)
    if "Mileage" in df.columns:
        df["Mileage"] = df["Mileage"].apply(
            lambda x: None if (pd.isna(x) or str(x).strip().upper() in ["NONE", "N/A", "NA", ""]) 
            else pd.to_numeric(x, errors="coerce")
        )

    # Round price columns to 2 decimal places
    for price_col in PRICE_COLUMNS:
        if price_col in df.columns:
            df[price_col] = df[price_col].round(2)
    
    return df


def real_order_mask(df: pd.DataFrame) -> pd.Series:
    """Return rows that contain actual order details, not blank sheet/formula rows."""
    if df is None or df.empty:
        return pd.Series(dtype=bool)

    cols = [c for c in REAL_ORDER_COLUMNS if c in df.columns]
    if not cols:
        return pd.Series(False, index=df.index)

    meaningful = pd.Series(False, index=df.index)
    for col in cols:
        series = df[col]
        if col in NUMERIC_COLUMNS:
            meaningful = meaningful | pd.to_numeric(series, errors="coerce").notna()
        else:
            meaningful = meaningful | series.fillna("").astype(str).str.strip().ne("")
    return meaningful


def real_orders_df(df: pd.DataFrame) -> pd.DataFrame:
    """Drop blank rows that only exist because formulas remain in Google Sheets."""
    if df is None or df.empty:
        return normalize_df(pd.DataFrame(columns=COLUMNS))
    return df.loc[real_order_mask(df)].copy()


def parse_order_date(date_value):
    if pd.isna(date_value) or str(date_value).strip() == "":
        return pd.NaT

    date_str = str(date_value).strip()
    for fmt in ["%Y-%m-%d", "%m/%d/%Y", "%m.%d.%Y", "%Y/%m/%d", "%m-%d-%Y"]:
        parsed = pd.to_datetime(date_str, format=fmt, errors="coerce")
        if pd.notna(parsed):
            return parsed
    return pd.to_datetime(date_str, errors="coerce")


def service_category(job_notes: str, part_name: str) -> str:
    text = f"{job_notes or ''} {part_name or ''}".lower()
    if any(word in text for word in ["brake", "pad", "rotor"]):
        return "Brakes"
    if any(word in text for word in ["spark", "ignition", "coil"]):
        return "Ignition"
    if any(word in text for word in ["check engine", "engine light", "diagnostic"]):
        return "Diagnostic"
    if any(word in text for word in ["wiper", "blade"]):
        return "Wipers"
    if any(word in text for word in ["seal", "rubber", "window"]):
        return "Seal / Trim"
    if str(job_notes or "").strip() or str(part_name or "").strip():
        return "Other"
    return "Uncategorized"


def dashboard_df(df: pd.DataFrame) -> pd.DataFrame:
    dfx = real_orders_df(df).copy()
    for col in PRICE_COLUMNS + ["Labor Time"]:
        dfx[col] = pd.to_numeric(dfx[col], errors="coerce").fillna(0)

    dfx["Date Parsed"] = pd.to_datetime(dfx["Date"].apply(parse_order_date), errors="coerce")
    dfx["Month"] = dfx["Date Parsed"].dt.to_period("M").dt.to_timestamp()
    dfx["Week"] = dfx["Date Parsed"].dt.to_period("W").dt.start_time
    dfx["Gross Margin %"] = dfx.apply(
        lambda row: (row["Profit"] / row["Total Price"] * 100) if row["Total Price"] else 0,
        axis=1,
    )
    dfx["Service Category"] = dfx.apply(
        lambda row: service_category(row.get("Job / Notes", ""), row.get("Part Name", "")),
        axis=1,
    )
    dfx["Paid Status"] = dfx["Paid?"].fillna("").astype(str).str.strip().replace("", "Unknown")
    dfx["Customer Display"] = dfx["Customer"].fillna("").astype(str).str.strip().replace("", "Missing customer")
    return dfx


def money(value) -> str:
    if pd.isna(value) or value == "":
        return "$0.00"
    return f"${float(value or 0):,.2f}"


def safe_divide_series(numerator: pd.Series, denominator: pd.Series) -> pd.Series:
    """Divide numeric Series and return zero where the denominator is zero or missing."""
    numerator_values = pd.to_numeric(numerator, errors="coerce").fillna(0).astype("float64")
    denominator_values = pd.to_numeric(denominator, errors="coerce").fillna(0).astype("float64")
    result = pd.Series(0.0, index=numerator.index, dtype="float64")
    valid = denominator_values.ne(0)
    result.loc[valid] = numerator_values.loc[valid].div(denominator_values.loc[valid])
    return result


